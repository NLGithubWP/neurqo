_MIXED_STEP_CSV = {
    "JOB": "job_step_action_times.csv",
    "STACK": "stack_step_action_times.csv",
    "TPCH": "tpch_step_action_times.csv",
}
_MIXED_PAIR_PATTERNS = (
    (0, 1, 0),
    (0, 1, 1),
    (0, 0, 1),
)


def _load_query_baselines(workload_key: str) -> dict[str, float]:
    """Load one baseline wall time per query from the workload step CSV."""
    root = Path(__file__).resolve().parents[1]
    csv_path = (
        root / "results" / "raw" / workload_key.lower() / _MIXED_STEP_CSV[workload_key]
    )
    baselines: dict[str, float] = {}
    with csv_path.open(newline="") as f:
        for row in csv.DictReader(f):
            qid = row["query_id"]
            # baseline_total_ms is the end-to-end PostgreSQL wall time per query.
            baselines.setdefault(qid, float(row["baseline_total_ms"]))
    if not baselines:
        raise ValueError(f"no baselines found in {csv_path}")
    return baselines


def _build_mixed_half_splits(workload_key: str) -> dict[str, dict[str, list[str]]]:
    """Build three 50/50 mixed folds with full test-union coverage.

    Strategy:
    1. Sort queries by baseline wall time (hard -> easy).
    2. Form adjacent pairs so each pair stays within the same difficulty band.
    3. Rotate which member of each pair goes to the test set of folds a/b/c.

    This keeps every fold close to a 50/50 train/test split while making the
    union of test queries across mixed_a/mixed_b/mixed_c cover the full workload.
    """
    baselines = _load_query_baselines(workload_key)
    ordered_qids = [
        qid
        for qid, _ in sorted(baselines.items(), key=lambda item: (-item[1], item[0]))
    ]
    tests = {fold: [] for fold in ("a", "b", "c")}

    pair_count = len(ordered_qids) // 2
    for pair_idx in range(pair_count):
        pair = ordered_qids[2 * pair_idx : 2 * pair_idx + 2]
        pattern = _MIXED_PAIR_PATTERNS[pair_idx % len(_MIXED_PAIR_PATTERNS)]
        for fold_idx, fold in enumerate(("a", "b", "c")):
            tests[fold].append(pair[pattern[fold_idx]])

    if len(ordered_qids) % 2 == 1:
        tests["c"].append(ordered_qids[-1])

    all_qids = set(ordered_qids)
    spec: dict[str, dict[str, list[str]]] = {}
    for fold in ("a", "b", "c"):
        test = sorted(tests[fold])
        train = sorted(all_qids - set(test))
        if set(train) | set(test) != all_qids or set(train) & set(test):
            raise ValueError(
                f"mixed split construction failed for {workload_key} mixed_{fold}"
            )
        spec[f"mixed_{fold}"] = {"train": train, "test": test}

    union_test = set().union(
        *(set(spec[f"mixed_{fold}"]["test"]) for fold in ("a", "b", "c"))
    )
    if union_test != all_qids:
        raise ValueError(
            f"mixed split test union does not cover full workload for {workload_key}"
        )

    return spec


